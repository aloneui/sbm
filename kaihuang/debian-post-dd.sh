#!/usr/bin/env bash
# Debian DD 后开荒脚本（按 David 定版顺序）
# DD 默认：bin456789/reinstall 装 Debian 13 最新版
# 主机名：用 David 给的昵称，空格换成“-”；没给昵称就停下来问他，不要自己编
# 已去掉：6. 建普通用户 / 8. 开 BBR（BBR 和 TCP 参数后面交给 tcpfit，不要在这里写）
# 顺序：验机 -> 更新 -> 时区 -> SSH+Fail2ban -> 防火墙 -> Swap -> 基础工具 -> 自动更新/日志 -> 收尾验证
set -uo pipefail

if [ "$(id -u)" -ne 0 ]; then echo "请用 root 运行"; exit 1; fi
if ! grep -qi debian /etc/os-release; then echo "此脚本只为 Debian 写，其他系统先停下确认"; exit 1; fi

DEFAULT_PUBKEY="ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIKPVtRt5lze6lYzEplNSCOuC8CT04C4Bc22j/kWlbwVo Generated By Termius"
LOG="/root/post-dd-check-$(date +%F-%H%M%S).txt"
echo "=== 开荒前验机记录将存到 $LOG ===" | tee "$LOG"

echo; echo ">>> [1/8] 验机：确认纯净"
{
  echo "--- os-release ---"; cat /etc/os-release
  echo "--- ip ---"; ip a; ip route
  echo "--- disk/mem ---"; df -h; free -h
  echo "--- listening ports ---"; ss -tulpn || true
  echo "--- users (shell) ---"; grep -E 'bash|sh$' /etc/passwd || true
  echo "--- root authorized_keys ---"; cat /root/.ssh/authorized_keys 2>/dev/null || echo "(无)"
  echo "--- crontab root ---"; crontab -l 2>/dev/null || echo "(无)"
  echo "--- crontab system ---"; ls -la /etc/cron.d/ 2>/dev/null; cat /etc/crontab 2>/dev/null
  echo "--- enabled services ---"; systemctl list-unit-files --state=enabled --no-pager || true
  echo "--- last login ---"; last -n 20 || true
} | tee -a "$LOG"
echo "验机输出已保存，自己扫一眼有没有陌生端口/用户/密钥/定时任务。按回车继续，Ctrl+C 退出"; read -r _

echo; echo ">>> [2/8] 全量更新"
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get full-upgrade -y
apt-get autoremove -y

echo; echo ">>> [3/8] 时区 + 时间同步"
read -r -p "时区 [默认 Asia/Shanghai，直接回车用默认]: " TZ_IN
timedatectl set-timezone "${TZ_IN:-Asia/Shanghai}"
timedatectl set-ntp true || true
timedatectl || true
# 主机名必须用 David 给的昵称：可通过环境变量 NICKNAME 传进来，没给就现场问，问不到就停
HN_IN="${NICKNAME:-}"
while [ -z "${HN_IN:-}" ]; do
  read -r -p "这台机的昵称是什么？(主机名要用它，没昵称不能继续): " HN_IN
done
# 空格（连续多个也算）统一换成“-”，去掉首尾的“-”
HN_CLEAN="$(echo "$HN_IN" | sed -E 's/[[:space:]]+/-/g; s/^-+//; s/-+$//')"
echo "主机名将设为: $HN_CLEAN"
hostnamectl set-hostname "$HN_CLEAN"

echo; echo ">>> [4/8] SSH 加固 + Fail2ban"
# 默认写入 David 的通用公钥（已存在则不重复加）
mkdir -p /root/.ssh; chmod 700 /root/.ssh; touch /root/.ssh/authorized_keys; chmod 600 /root/.ssh/authorized_keys
grep -qxF "$DEFAULT_PUBKEY" /root/.ssh/authorized_keys || echo "$DEFAULT_PUBKEY" >> /root/.ssh/authorized_keys
echo "已确保 root authorized_keys 里有默认通用公钥。"
echo "当前 SSH 端口/配置："; grep -RhsE '^[[:space:]]*(Port|PasswordAuthentication|PermitRootLogin)' /etc/ssh/sshd_config /etc/ssh/sshd_config.d/ 2>/dev/null || echo "(默认 22)"
read -r -p "新的 SSH 端口 [直接回车默认 49173]: " SSH_PORT_IN
SSH_PORT="${SSH_PORT_IN:-49173}"
apt-get install -y fail2ban
mkdir -p /etc/ssh/sshd_config.d
HARDEN=/etc/ssh/sshd_config.d/99-hardening.conf
: > "$HARDEN"
echo "Port $SSH_PORT" >> "$HARDEN"

# 默认公钥已在上一步写入，直接关闭密码登录（按 David 要求，不等试登确认）
cat >> "$HARDEN" <<'EOF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
PubkeyAuthentication yes
EOF
cat "$HARDEN"
sshd -t && (systemctl restart ssh || systemctl restart sshd) && systemctl enable --now fail2ban || true
echo "SSH 现在监听："; ss -tlnp | grep -E ":$SSH_PORT\b" || ss -tlnp

echo; echo ">>> [5/8] 防火墙 UFW（先放行 SSH，再启用）"
apt-get install -y ufw
ufw allow "$SSH_PORT/tcp"
read -r -p "要放行 80/443 吗？不建站就选 N [y/N]: " WEB_IN
if [[ "${WEB_IN:-}" =~ ^[Yy]$ ]]; then ufw allow 80/tcp; ufw allow 443/tcp; fi
ufw --force enable
ufw status verbose

echo; echo ">>> [6/8] Swap（已有 swap 自动跳过）"
if swapon --show | grep -q .; then
  echo "已有 swap，跳过"; free -h
else
  MEM_MB=$(free -m | awk '/^Mem:/{print $2}')
  if [ "$MEM_MB" -le 2048 ]; then SWAP_SIZE=2G; else SWAP_SIZE=1G; fi
  read -r -p "将创建 $SWAP_SIZE swap，确认 [Y/n]: " SWAP_OK
  if [[ ! "${SWAP_OK:-Y}" =~ ^[Nn]$ ]]; then
    fallocate -l "$SWAP_SIZE" /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=$(( ${SWAP_SIZE%G} * 1024 )) status=progress
    chmod 600 /swapfile; mkswap /swapfile; swapon /swapfile
    grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
    echo 'vm.swappiness=10' > /etc/sysctl.d/99-swap.conf; sysctl -p /etc/sysctl.d/99-swap.conf || true
  fi
  free -h
fi

echo; echo ">>> [7/8] 基础工具"
apt-get install -y curl wget git vim htop unzip tar ca-certificates gnupg lsb-release

echo; echo ">>> [8/8] 自动安全更新 + 日志瘦身 + 收尾验证"
apt-get install -y unattended-upgrades
dpkg-reconfigure -f noninteractive unattended-upgrades || true
mkdir -p /etc/systemd/journald.conf.d
printf '[Journal]\nSystemMaxUse=200M\nMaxRetentionSec=14day\n' > /etc/systemd/journald.conf.d/99-limit.conf
systemctl restart systemd-journald || true
echo "--- 收尾检查 ---" | tee -a "$LOG"
{ ss -tulpn; echo; ufw status verbose; echo; fail2ban-client status sshd 2>/dev/null || true; echo; timedatectl; } | tee -a "$LOG"
echo
echo "开荒完成。先不要关当前窗口：开新窗口用 ${SSH_PORT} 端口试登一次，成功后再 reboot。"
echo "验机/收尾记录在 $LOG"
